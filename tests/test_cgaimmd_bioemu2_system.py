@pytest.mark.bioemu2
def test_a_ligand_the_md_does_not_hold_is_refused():
    pytest.importorskip('bioemu2')
    spec = {'entities': [{'entity_type': 'protein', 'asym_ids': ['A'], 'sequence': 'LQGIVSWGSGCAQKNKPGVY'},
                         {'entity_type': 'ligand', 'asym_ids': ['L'], 'smiles': 'Oc1ccccc1'}]}
    with pytest.raises(ValueError, match=r"BioEmu2 ligand chain 'L' \(C6O, 7 bonds .*\) matches no molecule "
                                         r".* those are \['C7N2'\]"):
        BioEmu2System.build(spec, _md(PROTEIN_LIGAND))


@pytest.mark.bioemu2
def test_a_molecule_bioemu2_does_not_generate_is_refused():
    pytest.importorskip('bioemu2')
    spec = {'entities': [{'entity_type': 'protein', 'asym_ids': ['A'], 'sequence': 'LQGIVSWGSGCAQKNKPGVY'}]}
    with pytest.raises(ValueError, match='18 generator atoms can neither be generated by BioEmu2 nor placed'):
        BioEmu2System.build(spec, _md(PROTEIN_LIGAND))
    # with the generator atoms ending before the ligand, the protein alone maps
    system = BioEmu2System.build(spec, _md(PROTEIN_LIGAND, n_atoms=291))
    assert system.n_atoms == 291 and set(system.token_pools) == {'protein'}
