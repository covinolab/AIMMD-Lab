def test_residue_names():
    assert residue_name('HIE') == residue_name('HSD') == residue_name('hid') == 'HIS'
    assert residue_name('CYX') == residue_name('CYS2') == 'CYS'
    assert residue_name('NALA') == 'ALA' and residue_name('CHIE') == 'HIS' and residue_name('CASN') == 'ASN'
    assert residue_name('NLE') == 'NLE' and residue_name('SOL') == 'SOL' and residue_name('BEN') == 'BEN'


def test_elements_from_masses_undo_hydrogen_mass_repartitioning():
    # methyl group with repartitioned hydrogens (3.024 each), Ca2+, a virtual site, chlorine
    masses = [12.011 - 3 * 2.016, 3.024, 3.024, 3.024, 40.078, 0.0, 35.45, 14.0027]
    bonds = [(0, 1), (0, 2), (0, 3)]
    assert md_elements(masses, bonds) == ['C', 'H', 'H', 'H', 'Ca', 'X', 'Cl', 'N']
    with pytest.raises(ValueError, match='atom 0: mass 50 .* is no known element'):
        md_elements([50.0], [])


def test_kabsch_recovers_a_rigid_motion():
    rng = np.random.default_rng(0)
    p = rng.normal(size=(6, 3)) * 3
    rot = _rotation(rng)
    q = p @ rot + np.array([1.0, -2.0, 0.5])
    r, pc, qc = kabsch(p, q[None])
    assert np.allclose((p - pc) @ r[0] + qc[0], q, atol=1e-12)


def _toy_molecule():
    """A chain of 4 heavy atoms (known) with 3 hydrogens and an unmapped heavy atom (with a hydrogen), an
    ion near the chain and one far from it."""
    rng = np.random.default_rng(3)
    heavy = np.array([[0, 0, 0], [1.5, 0, 0], [2.0, 1.4, 0], [3.5, 1.5, 0.3]], float)
    template = np.concatenate([heavy, heavy[[0, 1, 2]] + rng.normal(scale=0.6, size=(3, 3)),
                               [[4.2, 2.6, 0.9], [4.0, 3.5, 1.2], [1.0, 1.5, 2.2], [12.0, 9.0, -7.0]]])
    elements = ['C', 'C', 'N', 'C', 'H', 'H', 'H', 'O', 'H', 'Ca', 'Na']
    bonds = [(0, 1), (1, 2), (2, 3), (0, 4), (1, 5), (2, 6), (3, 7), (7, 8)]
    return template, elements, bonds


def test_completion_places_every_other_atom_rigidly():
    template, elements, bonds = _toy_molecule()
    groups = completion_groups(len(template), [0, 1, 2, 3], bonds, elements, template, ion_cutoff=2.5)
    # heavy atoms first, then hydrogens (by parent), then the unbonded atoms
    assert groups[0] == ([7], [3, 2, 1])
    assert [g[0] for g in groups[1:5]] == [[4], [5], [6], [8]]
    assert groups[4] == ([8], [7, 3, 2])                  # the hydrogen of the placed O
    # Ca2+: the known heavy atom within 2.5 A (atom 2) and its heavy neighbours
    assert groups[5] == ([9], [1, 2, 3])
    # Na+, far from everything: the three nearest known heavy atoms (the placed O among them)
    assert groups[6] == ([10], [2, 3, 7])
    assert len(groups) == 7
    known = np.zeros((1,) + template.shape)
    known[:, :4] = template[:4]
    assert np.allclose(complete_from_groups(known, template, groups)[0], template, atol=1e-12)
    rng = np.random.default_rng(1)
    moved = template @ _rotation(rng) + rng.normal(size=3) * 10
    x = np.zeros((1,) + template.shape)
    x[:, :4] = moved[:4]
    assert np.allclose(complete_from_groups(x, template, groups)[0], moved, atol=1e-9)


def test_completion_names_atoms_that_cannot_be_placed():
    template, elements, bonds = _toy_molecule()
    template = np.concatenate([template, [[20, 20, 20], [21.4, 20, 20]]])
    elements = elements + ['C', 'C']                      # a second molecule nothing is known of
    with pytest.raises(ValueError, match='2 generator atoms can neither be generated by BioEmu2 nor placed '
                                         r'.*\[11, 12\].*n_atoms is too large'):
        completion_groups(len(template), [0, 1, 2, 3], bonds + [(11, 12)], elements, template)


