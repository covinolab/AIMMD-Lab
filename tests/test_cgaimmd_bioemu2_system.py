@pytest.mark.bioemu2
def test_peptide_map_is_the_old_chignolin_map(tiny_peptide_system, golden):
    system = tiny_peptide_system
    # extractor.heavy_atom_map of the archived chignolin campaign (CHARMM names: OT1 is BioEmu2's O)
    assert np.array_equal(system.bioemu2_to_md, golden['peptide.md_index'])
    md = system.md_atoms
    assert system.n_atoms == 166 and system.n_bioemu2_atoms == 92 and system.n_tokens == 10
    assert [md[a]['name'] for a in system.data['md_heavy_unmapped']] == ['OT2']
    names = [a['name'] for a in system.bioemu2_atoms]
    assert 'OXT' not in names
    o_last = [k for k, a in enumerate(system.bioemu2_atoms) if a['res_seq'] == 10 and a['name'] == 'O']
    assert [md[system.bioemu2_to_md[k]]['name'] for k in o_last] == ['OT1']
    # every non-glycine CA and the CB of the two threonines
    assert len(system.stereocenters()) == 9 + 2
    assert set(system.token_pools) == {'protein'}
    assert np.array_equal(system.core, np.arange(92))


@pytest.mark.bioemu2
def test_protein_ligand_map_is_the_old_trypsin_map(tiny_protein_ligand_system, golden):
    system = tiny_protein_ligand_system
    # the stored map of the archived trypsin campaign, restricted to these atoms (ligand: the first of the
    # four isomorphisms in sorted order)
    assert np.array_equal(system.bioemu2_to_md, golden['ligand.bioemu2_to_md'])
    ligand = system.ligands['L']
    assert ligand['spec'] == {'smiles': 'NC(=[NH2+])c1ccccc1'}
    assert ligand['n_isomorphisms'] == len(ligand['automorphisms']) == 4
    assert ''.join(ligand['elements']) == 'CCCCCCCNN' and len(ligand['bonds']) == 9
    assert np.array_equal(system.ligand_bioemu2_atoms, np.arange(146, 155))
    assert system.data['md_heavy_unmapped'] == []
    # the old constants: core CA atoms, reference pose, token pools within 6 A of the ligand
    assert np.array_equal(system.core, golden['ligand.constants.core_be2'])
    assert np.allclose(system.reference[system.core], golden['ligand.constants.ref_core'], atol=1e-5)
    assert np.array_equal(system.token_idx_at_atom, golden['ligand.constants.token_idx_at_atom'])
    for name in ('ligand', 'pocket', 'protein'):
        assert np.array_equal(system.token_pools[name], golden[f'ligand.constants.{name}_tokens']), name
    # 16 non-glycine CA and the CB of Ile; benzamidinium has no stereocenter
    assert len(system.stereocenters()) == 17
    assert np.allclose(system.template, golden['ligand.x_md_reference'], atol=1e-5)


@pytest.mark.bioemu2
@pytest.mark.parametrize('which', ['peptide', 'protein_ligand'])
def test_atom_map_round_trip(which, tiny_peptide_system, tiny_protein_ligand_system):
    system = tiny_peptide_system if which == 'peptide' else tiny_protein_ligand_system
    rng = np.random.default_rng(7)
    # BioEmu2 -> generator atoms -> BioEmu2 is exact, also with BioEmu2's padding rows
    b = rng.normal(size=(3, system.n_bioemu2_atoms + 5, 3)) * 20
    full = system.complete(b)
    assert full.shape == (3, system.n_atoms, 3) and np.array_equal(system.to_bioemu2(full), b[:, :-5])
    assert np.array_equal(system.to_bioemu2(full.reshape(3, -1)), b[:, :-5])
    assert np.array_equal(system.to_bioemu2(full[0]), b[0, :-5]) and system.complete(b[0]).shape == full[0].shape
    # the template completes to itself, and a rigidly moved structure to the moved structure
    template = system.template
    assert np.allclose(system.complete(system.to_bioemu2(template[None]))[0], template, atol=1e-9)
    moved = template @ _rotation(rng) + rng.normal(size=3) * 30
    assert np.allclose(system.complete(system.to_bioemu2(moved)), moved, atol=1e-8)
    # the placed atoms stay where a bond puts them in a noisy structure
    noisy = system.to_bioemu2(template) + rng.normal(scale=0.05, size=(system.n_bioemu2_atoms, 3))
    done = system.complete(noisy)
    bonds = np.array([(i, j) for i, j in _bonds(system) if i not in set(system.bioemu2_to_md)
                      or j not in set(system.bioemu2_to_md)])
    lengths = np.linalg.norm(done[bonds[:, 0]] - done[bonds[:, 1]], axis=1)
    reference = np.linalg.norm(template[bonds[:, 0]] - template[bonds[:, 1]], axis=1)
    assert np.abs(lengths - reference).max() < 0.25


def _bonds(system):
    from aimmd.cgaimmd.bioemu2.build import read_md_atoms
    data = PEPTIDE if system.n_atoms == 166 else PROTEIN_LIGAND
    return [tuple(b) for b in read_md_atoms(data / 'md.gro', data / 'md.top').bonds]


@pytest.mark.bioemu2
def test_a_saved_system_loads_without_the_check(tiny_peptide_system, tmp_path):
    folder = tmp_path / 'copy'
    shutil.copytree(tiny_peptide_system.folder, folder)
    loaded = BioEmu2System.load(folder, check=False)
    assert loaded.data == tiny_peptide_system.data and loaded.folder == folder
    assert loaded.trunk_path == folder / 'trunk_embeddings.pt'
    assert np.array_equal(loaded.complete(loaded.to_bioemu2(loaded.template)), tiny_peptide_system.complete(
        tiny_peptide_system.to_bioemu2(tiny_peptide_system.template)))


@pytest.mark.bioemu2
def test_a_folder_of_another_bioemu2_version_is_refused(tiny_peptide_system, tmp_path):
    folder = tmp_path / 'copy'
    shutil.copytree(tiny_peptide_system.folder, folder)
    data = json.loads((folder / 'system.json').read_text())
    data['bioemu2_version'] = '0.0.1'
    (folder / 'system.json').write_text(json.dumps(data))
    with pytest.raises(ValueError, match='was built with bioemu2 0.0.1, bioemu2 .* is installed'):
        BioEmu2System.load(folder)
    assert BioEmu2System.load(folder, allow_version_mismatch=True).bioemu2_version == '0.0.1'


def _md(data, n_atoms=None):
    from aimmd.cgaimmd.bioemu2.build import read_md_atoms
    return read_md_atoms(data / 'md.gro', data / 'md.top', n_atoms=n_atoms)


